# Função para rodar a Análise de Correspondência para a P22 filtrada por rotação e retornar os resultados em tabelas
def extrair_resultados_por_rota(rota):
    # Filtrar o DataFrame para manter apenas as colunas específicas de P22 e a rotação especificada
    colunas = [f'P22#{palavra}' for palavra in palavras]
    df_filtrado = df[df['ROTACION'] == rota][colunas]

    # Substituir NaNs e infinitos por zero
    df_filtrado = df_filtrado.replace([float('inf'), -float('inf')], float('nan')).fillna(0)

    # Realizando a Análise de Correspondência
    ca = prince.CA(n_components=2)
    ca = ca.fit(df_filtrado)

    # Pegando as coordenadas das colunas (palavras)
    col_coords = ca.column_coordinates(df_filtrado)
    col_coords.columns = ['Dimensão 1', 'Dimensão 2']

    # Calculando as contribuições manuais das colunas
    eigenvalues = ca.eigenvalues_
    total_inertia = sum(eigenvalues)
    contrib_dim1 = (col_coords['Dimensão 1'] ** 2) / total_inertia
    contrib_dim2 = (col_coords['Dimensão 2'] ** 2) / total_inertia
    contrib = pd.DataFrame({
        'Contribuição Dimensão 1': contrib_dim1,
        'Contribuição Dimensão 2': contrib_dim2
    })

    # Calculando as inércias manualmente (percentual da variância explicada por cada dimensão)
    inertia_dim1 = eigenvalues[0] / total_inertia
    inertia_dim2 = eigenvalues[1] / total_inertia

    # Criar DataFrames para visualização
    print(f"Resultados para {rotacion_map[rota]}:")
    print("\nCoordenadas das Palavras:")
    display(col_coords)

    print("\nContribuições das Palavras para Cada Dimensão:")
    display(contrib)

    print("\nInércias Explicadas por Dimensão:")
    print(f"Dimensão 1: {inertia_dim1:.2%}, Dimensão 2: {inertia_dim2:.2%}")
    print("\n" + "="*50 + "\n")

