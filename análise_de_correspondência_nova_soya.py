df = pd.read_excel('OKNOBR_BD_BUNGE3.xlsx')

# Lista de palavras (assumindo que são numeradas de 1 a 41)
palavras = [f'{i}' for i in range(1, 42)]

# Função para rodar a Análise de Correspondência para cada conjunto de colunas
def rodar_analise_por_conjunto(prefixo):
    # Filtrar as colunas que começam com o prefixo (P22, P32 ou P42)
    colunas = [f'{prefixo}#{palavra}' for palavra in palavras]

    # Filtrar o DataFrame para manter apenas as colunas específicas
    df_subset = df[colunas]

    # Verificar se há valores NaN ou infinitos e exibir uma mensagem se houver
    if df_subset.isnull().values.any() or not df_subset.applymap(pd.api.types.is_number).all().all():
        print(f"Valores NaN ou não numéricos encontrados no conjunto {prefixo}. Substituindo por zero.")

    # Substituir NaNs e infinitos por zero
    df_subset = df_subset.replace([float('inf'), -float('inf')], float('nan')).fillna(0)

    # Verificar novamente se ainda há algum valor inválido
    if df_subset.isnull().values.any():
        print("Ainda há valores NaN após a substituição.")
        return
    if not df_subset.applymap(pd.api.types.is_number).all().all():
        print("Ainda há valores não numéricos após a substituição.")
        return

    # Realizando a Análise de Correspondência
    ca = prince.CA(n_components=2)
    ca = ca.fit(df_subset)

    # Pegando as coordenadas das linhas e colunas
    row_coords = ca.row_coordinates(df_subset)
    col_coords = ca.column_coordinates(df_subset)

    # Plotando o gráfico manualmente
    plt.figure(figsize=(8, 6))
    plt.scatter(row_coords[0], row_coords[1], alpha=0.5, label='Rows')
    plt.scatter(col_coords[0], col_coords[1], alpha=0.5, label='Columns', color='red')

    # Adicionando labels para as colunas
    for i, (x, y) in enumerate(zip(col_coords[0], col_coords[1])):
        plt.text(x, y, colunas[i], fontsize=8, color='red', ha='right')

    plt.title(f'Análise de Correspondência - Conjunto {prefixo}')
    plt.xlabel('Dimensão 1')
    plt.ylabel('Dimensão 2')
    plt.legend()
    plt.show()

